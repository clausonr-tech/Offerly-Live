async function main() {
  ({ db, close: closeDb } = await openScriptDb());
  const wantedEmail = process.env.SEED_USER_EMAIL;
  const user = wantedEmail
    ? await db.query.users.findFirst({ where: eq(schema.users.email, wantedEmail) })
    : await db.query.users.findFirst();
  if (!user) {
    throw new Error(
      wantedEmail
        ? `No user with email ${wantedEmail}.`
        : "No user found — sign up through the app first, then re-run this script.",
    );
  }
  console.log(`Seeding contacts for ${user.email}.`);

  // Clear out the old pilot-batch contacts (superseded by this full import) with
  // simple per-row deletes - no RETURNING, no cascade, mirrors the app's own
  // deleteContact action, which is a proven-safe query shape on this database.
  const existingContacts = await db.query.contacts.findMany({ where: eq(schema.contacts.userId, user.id) });
  for (const c of existingContacts) {
    await db.delete(schema.contacts).where(eq(schema.contacts.id, c.id));
  }
  console.log(`Removed ${existingContacts.length} existing contacts.`);

  // One multi-row insert inside a transaction, not 289 separate statements:
  // each statement makes PGlite flush its pages, which is the difference
  // between a second and several minutes on a slow filesystem.
  await db.transaction(async (tx) => {
    await tx.insert(schema.contacts).values(
      CONTACTS.map((c) => ({
        userId: user.id,
        name: c.name,
        firm: c.firm,
        role: c.role,
        email: c.email,
        sourceUrl: c.sourceUrl,
        background: c.background,
        enrichedAt: new Date(),
      })),
    );
  });

  console.log(`Inserted ${CONTACTS.length} contacts.`);
  // close(), not process.exit(): exiting here can cut the process off before
  // PGlite has flushed, leaving a database that is missing rows this script
  // just reported inserting.
  await closeDb();
}

