"use client";

import { useMemo, useState } from "react";

/** One matched person at one matched firm, as the draft form offers them. */
export type RecipientOption = {
  /** "contact-<id>" for the student's own contacts, "directory-<id>" for directory people. */
  key: string;
  name: string;
  title: string | null;
  firmKey: string;
  firmName: string;
  /** What the firm recruits for, e.g. "Investment Banking" - shown to the model, not picked. */
  firmDivisions: string[];
  linkedinUrl: string | null;
  /** Their school, when known - "Not an alum" is only filled in from a real one. */
  school: string | null;
  /** How they came to be on the list: generated by contact sourcing, saved by
   *  the student, or one of the directory people they were matched with. */
  found: "offerly" | "saved" | "directory";
  /** The latest cold email drafted to them in Offerly, which follow-ups are built from. */
  priorCold: { subject: string; draftedOn: string } | null;
  /** When follow-up #1 to them was drafted in Offerly, if it was. */
  priorFollowUp1On: string | null;
  /** Overlaps the app detected, pre-filled into the common-ground box. */
  commonGround: string;
};

// Same one-line box and label layout as the rest of the draft form, so the
// company, person and type selects sit on one line.
const selectClass =
  "block h-11 w-full rounded-md border border-brand-200 px-3 py-2 text-sm leading-6 text-brand-900 focus:border-accent-500 focus:outline-none disabled:opacity-50";

/**
 * Company, then person - only from the student's matches.
 *
 * No division step: a matched firm has a handful of matched people, not a
 * hundred, so a third select only slows the choice down. The firm's divisions
 * still reach the model, which tailors the email to the right group.
 *
 * Renders two grid cells, so it drops into the parent form's row.
 */
export default function RecipientPicker({
  recipients,
  onSelect,
  initialKey,
}: {
  recipients: RecipientOption[];
  onSelect: (key: string) => void;
  /** Someone arrived here to write to one person - see /outreach?contact=. */
  initialKey?: string;
}) {
  // Both selects start on whoever was linked to, so the form opens on the
  // person rather than on "Choose a matched company". Only the initial value:
  // the student is free to change it, and changing the company still clears
  // the person.
  const preselected = initialKey ? recipients.find((r) => r.key === initialKey) : undefined;
  const [firmKey, setFirmKey] = useState(preselected?.firmKey ?? "");
  const [key, setKey] = useState(preselected?.key ?? "");

  const companies = useMemo(() => {
    const byKey = new Map<string, { name: string; count: number }>();
    for (const r of recipients) {
      const entry = byKey.get(r.firmKey) ?? { name: r.firmName, count: 0 };
      entry.count += 1;
      byKey.set(r.firmKey, entry);
    }
    return [...byKey.entries()]
      .map(([k, v]) => ({ key: k, ...v }))
      .sort((a, b) => a.name.localeCompare(b.name));
  }, [recipients]);

  const people = useMemo(
    () => recipients.filter((r) => r.firmKey === firmKey).sort((a, b) => a.name.localeCompare(b.name)),
    [recipients, firmKey],
  );

  return (
    <>
      <label className="flex h-full flex-col">
        <span className="mb-1 block text-sm font-semibold text-brand-900">Company</span>
        <select
          value={firmKey}
          onChange={(e) => {
            // Clearing the person is the point: someone left selected under a
            // company they don't work at is how the wrong person gets emailed.
            setFirmKey(e.target.value);
            setKey("");
            onSelect("");
          }}
          className={`${selectClass} mt-auto`}
        >
          <option value="">Choose a matched company</option>
          {companies.map((c) => (
            <option key={c.key} value={c.key}>
              {c.name} ({c.count})
            </option>
          ))}
        </select>
      </label>

      <label className="flex h-full flex-col">
        <span className="mb-1 block text-sm font-semibold text-brand-900">Person</span>
        <select
          name="recipient"
          required
          value={key}
          disabled={!firmKey}
          onChange={(e) => {
            setKey(e.target.value);
            onSelect(e.target.value);
          }}
          className={`${selectClass} mt-auto`}
        >
          <option value="" disabled>
            {firmKey ? "Choose a person" : "Choose a company first"}
          </option>
          {people.map((p) => (
            <option key={p.key} value={p.key}>
              {p.title ? `${p.name} - ${p.title}` : p.name}
            </option>
          ))}
        </select>
      </label>
    </>
  );
}
