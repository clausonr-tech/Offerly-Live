
// Two quality checks that need no model: whether a story is still a rumour,
// and whether a photo says it was made by an AI.

// ------------------------------------------------------------------ rumours

// The words a story uses when its facts are not yet on the record: unnamed
// sources, talks that have not concluded, a firm "weighing" or "exploring"
// something. The story is still news - often the most valuable kind - but a
// student repeating it should know it is unconfirmed.
const RUMOUR_RE =
  /\b(sources? (?:say|said|familiar|close)|people (?:familiar|close|briefed|with knowledge)|according to (?:people|sources|a person|two people|three people)|person familiar|reportedly|is said to|are said to|said to be|in (?:advanced |early |exclusive )?talks|nears? (?:a )?deal|weighs?|weighing|explores?|exploring|mulls?|mulling|considering|rumou?r|exclusive:|plans? to explore|could (?:buy|sell|merge|acquire|bid)|in discussions)\b/i;

export function hasRumourLanguage(title: string, description: string | null = null): boolean {
  return RUMOUR_RE.test(title) || (description !== null && RUMOUR_RE.test(description.slice(0, 200)));
}

/**
 * An event is unconfirmed when every report of it uses rumour language, only
 * one outlet carries it, and no official source (a filing or a regulator) is
 * among them. A second outlet or a filing confirms it and the tag comes off.
 */
export function isUnconfirmed(
  members: { title: string; description: string | null; tier: string }[],
  outlets: number,
): boolean {
  if (outlets >= 2) return false;
  if (members.some((m) => m.tier === "primary")) return false;
  return members.every((m) => hasRumourLanguage(m.title, m.description));
}

// ------------------------------------------------------------------ AI images

// What an image file says about itself. Publishers and photo agencies that
// label AI imagery do it in the file's metadata:
//   - IPTC "digital source type" (the industry standard, in XMP):
//     trainedAlgorithmicMedia, compositeWithTrainedAlgorithmicMedia,
//     algorithmicMedia - generated or partly generated by a model.
//   - C2PA content credentials, whose assertions carry the same terms.
//   - Generator names written by the tools themselves.
// Absence proves nothing - most AI images carry no label - which is why the
// first defence is per-source (only sources checked to use real photography
// show photos at all). This catches the labelled ones that get past that.
const AI_MARKERS: [RegExp, string][] = [
  [/trainedAlgorithmicMedia/i, "IPTC: generated by AI"],
  [/compositeWithTrainedAlgorithmicMedia/i, "IPTC: partly generated by AI"],
  [/digitalsourcetype\/algorithmicMedia/i, "IPTC: algorithmic media"],
  [/\bc2pa\.ai_generative_training|c2pa\.actions[\s\S]{0,400}(?:created|edited)[\s\S]{0,400}trainedAlgorithmic/i, "C2PA: AI-generated"],
  // Only in the fields that record which tool MADE the file. Anywhere else it
  // is a caption: Insurance Journal's photo of a phone showing OpenAI lists
  // "dall-e" among its keywords and is a real photograph.
  [
    /(?:CreatorTool|Software|softwareAgent)["'=:>\s]{1,6}[^<"\n]{0,40}\b(Midjourney|DALL[-·]?E|Stable Diffusion|Adobe Firefly|Imagen|Ideogram|Leonardo\.ai|NovelAI)\b/i,
    "made by an AI generator (metadata)",
  ],
];

/** The reason an image's own metadata marks it as AI-made, or null. */
export function aiImageMarker(bytes: string): string | null {
  for (const [re, reason] of AI_MARKERS) if (re.test(bytes)) return reason;
  return null;
}

