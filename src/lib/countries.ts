// Most students are from here, so it leads the list when the box is empty.
export const COUNTRY_OPTIONS: readonly string[] = ["United States", ...COUNTRIES.filter((c) => c !== "United States")];

/** The listed spelling of a typed country, matched ignoring case, or null. */
export function canonicalCountry(typed: string): string | null {
  const t = typed.trim().toLowerCase();
  if (!t) return null;
  return COUNTRIES.find((c) => c.toLowerCase() === t) ?? null;
}
